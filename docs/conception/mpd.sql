-- Prêt'Outil : modèle physique de données (PostgreSQL 16)
-- Ticket #2. Script de référence : à J3, le schéma est créé par les migrations
-- Doctrine ; les contraintes CHECK et EXCLUDE ci-dessous y sont recopiées à la main.
-- Conventions : snake_case, tables au singulier, clé primaire id,
-- clé étrangère <table>_id, dates d'action en <action>_le.

BEGIN;

-- Nécessaire pour combiner l'égalité sur objet_id (btree) et le chevauchement
-- de périodes (gist) dans une même contrainte d'exclusion (RG2).
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Recherche par nom sans tenir compte des accents (#109) : unaccent(objet.nom).
CREATE EXTENSION IF NOT EXISTS unaccent;

-- ---------------------------------------------------------------------------
-- utilisateur
-- ---------------------------------------------------------------------------
CREATE TABLE utilisateur (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    email                 VARCHAR(180) NOT NULL,
    mot_de_passe          VARCHAR(255) NOT NULL,
    nom                   VARCHAR(100) NOT NULL,
    prenom                VARCHAR(100) NOT NULL,
    telephone             VARCHAR(20),
    roles                 JSON         NOT NULL DEFAULT '[]',
    actif                 BOOLEAN      NOT NULL DEFAULT TRUE,
    cree_le               TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    derniere_activite_le  TIMESTAMP(0),
    CONSTRAINT pk_utilisateur PRIMARY KEY (id),
    CONSTRAINT uq_utilisateur_email UNIQUE (email),
    -- L'application normalise l'email en minuscules : la base refuse toute variante.
    CONSTRAINT ck_utilisateur_email_minuscules CHECK (email = LOWER(email))
);

COMMENT ON TABLE utilisateur IS 'Adhérents, gestionnaires et administrateurs';
COMMENT ON COLUMN utilisateur.mot_de_passe IS 'Empreinte (hasher Symfony auto), jamais le mot de passe en clair';
COMMENT ON COLUMN utilisateur.derniere_activite_le IS 'RGPD : point de départ de la durée de conservation de 3 ans';

-- ---------------------------------------------------------------------------
-- categorie
-- ---------------------------------------------------------------------------
CREATE TABLE categorie (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    libelle  VARCHAR(50) NOT NULL,
    CONSTRAINT pk_categorie PRIMARY KEY (id),
    CONSTRAINT uq_categorie_libelle UNIQUE (libelle)
);

-- ---------------------------------------------------------------------------
-- objet
-- ---------------------------------------------------------------------------
CREATE TABLE objet (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY,
    categorie_id      INTEGER      NOT NULL,
    nom               VARCHAR(120) NOT NULL,
    description       TEXT         NOT NULL,
    caracteristiques  TEXT,
    image             VARCHAR(100),
    etat              VARCHAR(20)  NOT NULL DEFAULT 'bon',
    actif             BOOLEAN      NOT NULL DEFAULT TRUE,
    cree_le           TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_objet PRIMARY KEY (id),
    CONSTRAINT fk_objet_categorie FOREIGN KEY (categorie_id)
        REFERENCES categorie (id) ON DELETE RESTRICT,
    CONSTRAINT ck_objet_etat CHECK (etat IN ('bon', 'abime', 'hors_service')),
    -- Nom simple d'une photo de public/uploads/objets/ : aucun chemin ne peut être enregistré
    CONSTRAINT ck_objet_image CHECK (image ~ '^[a-z0-9-]+\.webp$')
);

CREATE INDEX idx_objet_categorie ON objet (categorie_id);

-- ---------------------------------------------------------------------------
-- reservation
-- ---------------------------------------------------------------------------
CREATE TABLE reservation (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    utilisateur_id  INTEGER      NOT NULL,
    objet_id        INTEGER      NOT NULL,
    date_debut      DATE         NOT NULL,
    date_fin        DATE         NOT NULL,
    statut          VARCHAR(20)  NOT NULL DEFAULT 'confirmee',
    cree_le         TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sortie_le       TIMESTAMP(0),
    sortie_par_id   INTEGER,
    retour_le       TIMESTAMP(0),
    retour_par_id   INTEGER,
    etat_retour     VARCHAR(20),
    CONSTRAINT pk_reservation PRIMARY KEY (id),
    CONSTRAINT fk_reservation_utilisateur FOREIGN KEY (utilisateur_id)
        REFERENCES utilisateur (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservation_objet FOREIGN KEY (objet_id)
        REFERENCES objet (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservation_sortie_par FOREIGN KEY (sortie_par_id)
        REFERENCES utilisateur (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservation_retour_par FOREIGN KEY (retour_par_id)
        REFERENCES utilisateur (id) ON DELETE RESTRICT,
    CONSTRAINT ck_reservation_statut
        CHECK (statut IN ('confirmee', 'en_cours', 'terminee', 'annulee')),
    CONSTRAINT ck_reservation_etat_retour
        CHECK (etat_retour IS NULL OR etat_retour IN ('bon', 'abime', 'hors_service')),
    -- RG1 (partie vérifiable en base ; « pas dans le passé » dépend de la date du jour, contrôlé par le service)
    CONSTRAINT ck_reservation_dates CHECK (date_fin >= date_debut),
    -- Une sortie a toujours une date et un gestionnaire, ou ni l'un ni l'autre.
    CONSTRAINT ck_reservation_sortie
        CHECK ((sortie_le IS NULL) = (sortie_par_id IS NULL)),
    -- Un retour a une date, un gestionnaire et un état, ou rien.
    CONSTRAINT ck_reservation_retour
        CHECK ((retour_le IS NULL AND retour_par_id IS NULL AND etat_retour IS NULL)
            OR (retour_le IS NOT NULL AND retour_par_id IS NOT NULL AND etat_retour IS NOT NULL)),
    CONSTRAINT ck_reservation_retour_apres_sortie
        CHECK (retour_le IS NULL OR (sortie_le IS NOT NULL AND retour_le >= sortie_le)),
    -- Cycle de vie : le statut est cohérent avec les dates de sortie et de retour.
    CONSTRAINT ck_reservation_cycle_de_vie CHECK (
           (statut IN ('confirmee', 'annulee') AND sortie_le IS NULL     AND retour_le IS NULL)
        OR (statut = 'en_cours'                AND sortie_le IS NOT NULL AND retour_le IS NULL)
        OR (statut = 'terminee'                AND sortie_le IS NOT NULL AND retour_le IS NOT NULL)
    ),
    -- RG2 : deux réservations actives d'un même objet ne peuvent pas se chevaucher.
    -- Bornes incluses '[]' : un objet rendu le 20 ne peut pas être réservé à partir du 20.
    CONSTRAINT ex_reservation_chevauchement EXCLUDE USING gist (
        objet_id WITH =,
        daterange(date_debut, date_fin, '[]') WITH &&
    ) WHERE (statut IN ('confirmee', 'en_cours'))
);

-- RG4 : compter les réservations actives d'un adhérent.
CREATE INDEX idx_reservation_utilisateur_statut ON reservation (utilisateur_id, statut);
CREATE INDEX idx_reservation_objet ON reservation (objet_id);
CREATE INDEX idx_reservation_sortie_par ON reservation (sortie_par_id);
CREATE INDEX idx_reservation_retour_par ON reservation (retour_par_id);

COMMIT;

-- ---------------------------------------------------------------------------
-- Droits minimaux de l'utilisateur applicatif
-- ---------------------------------------------------------------------------
-- L'application ne se connecte jamais avec le propriétaire du schéma.
-- Le mot de passe est défini hors du dépôt : ALTER ROLE pretoutil_app PASSWORD '...';
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'pretoutil_app') THEN
        CREATE ROLE pretoutil_app LOGIN;
    END IF;
END
$$;

GRANT USAGE ON SCHEMA public TO pretoutil_app;
GRANT SELECT, INSERT, UPDATE ON utilisateur, categorie, objet, reservation TO pretoutil_app;
-- Suppression physique autorisée uniquement pour un objet jamais réservé (US6) ;
-- la clé étrangère ON DELETE RESTRICT bloque les autres cas.
GRANT DELETE ON objet TO pretoutil_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO pretoutil_app;
